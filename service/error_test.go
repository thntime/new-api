func TestResetStatusCodeAppliesErrorStatusMapping(t *testing.T) {
	previous := operation_setting.ErrorStatusMappingRules
	t.Cleanup(func() { operation_setting.ErrorStatusMappingRules = previous })

	matchingRules, err := operation_setting.ParseErrorStatusMappingRules(`[{"name":"Rate limit","enabled":true,"match":{"status_code":0,"message_regex":"exhausted|tpm/rpm|rps|rate limit"},"output":{"status_code":429,"message":"rate limit exceeded","type":"rate_limit_error","code":"rate_limit_exceeded","headers":[{"key":"x-should-retry","value":"true"},{"key":"Retry-After","value":"30"}]}}]`)
	require.NoError(t, err)

	t.Run("no rules leaves the error untouched", func(t *testing.T) {
		operation_setting.ErrorStatusMappingRules = nil
		newAPIError := &types.NewAPIError{StatusCode: 429, Err: errors.New("inference exceeds tpm/rpm limit")}

		ResetStatusCode(newAPIError, "")

		assert.Nil(t, newAPIError.ResponseOverride)
		assert.Equal(t, 429, newAPIError.StatusCode)
		assert.EqualError(t, newAPIError.Err, "inference exceeds tpm/rpm limit")
	})

	t.Run("matching rule sets only the response override", func(t *testing.T) {
		operation_setting.ErrorStatusMappingRules = matchingRules
		newAPIError := &types.NewAPIError{StatusCode: 200, Err: errors.New("inference exceeds tpm/rpm limit")}

		ResetStatusCode(newAPIError, "")

		require.NotNil(t, newAPIError.ResponseOverride)
		assert.Equal(t, 429, newAPIError.ResponseOverride.StatusCode)
		assert.Equal(t, map[string]string{"x-should-retry": "true", "Retry-After": "30"}, newAPIError.ResponseOverride.Headers)
		assert.Equal(t, "rate limit exceeded", newAPIError.ResponseOverride.Message)
		assert.Equal(t, "rate_limit_error", newAPIError.ResponseOverride.Type)
		assert.Equal(t, "rate_limit_exceeded", newAPIError.ResponseOverride.Code)
		assert.Equal(t, 200, newAPIError.StatusCode)
		assert.EqualError(t, newAPIError.Err, "inference exceeds tpm/rpm limit")
	})
}

func TestResetStatusCode(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name             string
		statusCode       int
		statusCodeConfig string
		expectedCode     int
	}{
		{
			name:             "map string value",
			statusCode:       429,
			statusCodeConfig: `{"429":"503"}`,
			expectedCode:     503,
		},
		{
			name:             "map int value",
			statusCode:       429,
			statusCodeConfig: `{"429":503}`,
			expectedCode:     503,
		},
		{
			name:             "skip invalid string value",
			statusCode:       429,
			statusCodeConfig: `{"429":"bad-code"}`,
			expectedCode:     429,
		},
		{
			name:             "skip status code 200",
			statusCode:       200,
			statusCodeConfig: `{"200":503}`,
			expectedCode:     200,
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			newAPIError := &types.NewAPIError{
				StatusCode: tc.statusCode,
			}
			ResetStatusCode(newAPIError, tc.statusCodeConfig)
			require.Equal(t, tc.expectedCode, newAPIError.StatusCode)
		})
	}
}

func TestRelayErrorHandlerTruncatesInvalidJSONBodyInLog(t *testing.T) {
	withDebugEnabled(t, false)

	body := strings.Repeat("b", common.LocalLogContentLimit+256)
	var logBuffer bytes.Buffer

	common.LogWriterMu.Lock()
	oldWriter := gin.DefaultErrorWriter
	gin.DefaultErrorWriter = &logBuffer
	common.LogWriterMu.Unlock()
	t.Cleanup(func() {
		common.LogWriterMu.Lock()
		gin.DefaultErrorWriter = oldWriter
		common.LogWriterMu.Unlock()
	})

	resp := &http.Response{
		StatusCode: http.StatusInternalServerError,
		Body:       io.NopCloser(strings.NewReader(body)),
	}

	newAPIError := RelayErrorHandler(context.Background(), resp, false)

	require.NotNil(t, newAPIError)
	require.Equal(t, "bad response status code 500", newAPIError.Error())
	require.Contains(t, logBuffer.String(), "[truncated")
	require.Contains(t, logBuffer.String(), fmt.Sprintf("original_length=%d", len(body)))
	require.NotContains(t, logBuffer.String(), strings.Repeat("b", common.LocalLogContentLimit+1))
}

func TestRelayErrorHandlerKeepsStructuredErrorMessage(t *testing.T) {
	message := strings.Repeat("c", common.LocalLogContentLimit+256)
	body := `{"message":"` + message + `"}`
	resp := &http.Response{
		StatusCode: http.StatusInternalServerError,
		Body:       io.NopCloser(strings.NewReader(body)),
	}

	newAPIError := RelayErrorHandler(context.Background(), resp, false)

	require.NotNil(t, newAPIError)
	require.Equal(t, message, newAPIError.Error())
}

